public class Car {
    String name;
    int price;
    String fuel;
    int mileage;
    int safety;

    Car(String name, int price, String fuel, int mileage, int safety) {
        this.name = name;
        this.price = price;
        this.fuel = fuel;
        this.mileage = mileage;
        this.safety = safety;
    }
}
